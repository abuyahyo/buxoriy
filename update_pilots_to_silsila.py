import json
import sys

OVERRIDES = {
    # h239 (k4 Таҳорат, 73-БОБ) — app пайдар-пай "238, 239"да кўрсатади
    239: {
        "rowi": "Абдурраҳмон ибн Ҳурмуз Аъраж сўзлаб берди",
        "matn": "(Абу Ямон) ушбу иснод билан айтади: «Бирортангиз оқмайдиган турғун сувга бавл қилмасин, (чунки) кейин унда ғусл қилиши бор».",
    },
    # h897 (k11 Жума) — app битта ғусл-сўз кўрсатади, мен 2 марта ёзган эдим
    897: {
        "rowi": "Абу Ҳурайра розияллоҳу анҳу айтади",
        "matn": "«Расулуллоҳ соллаллоҳу алайҳи васаллам: «Биз (дунёда) охиргилармиз, қиёмат куни пешқадамлармиз. Уларга биздан олдин китоб берилган, бизга эса улардан кейин берилган. Ушбу кун улар ихтилоф қилган нарсадир. Бас, Аллоҳ бизни (бу кунга) ҳидоят қилди. Эрта яҳудийларники, индин насороларникидир», дедилар-да, сукут қилдилар. Сўнг: «Ҳар етти кунда бир марта боши ва баданини ювиш ҳар бир мусулмон зиммасидаги ҳақдир», дедилар».",
    },
}


def main():
    with open("data.json", "r", encoding="utf-8") as f:
        db = json.load(f)

    applied = []
    for k in db:
        for b in k.get("boblar", []):
            for h in b.get("hadislar", []):
                if h["id"] in OVERRIDES:
                    tr = OVERRIDES[h["id"]]
                    h["matn"] = tr["matn"]
                    h["rowi"] = tr["rowi"]
                    if tr.get("izoh"):
                        h["izoh"] = tr["izoh"]
                    applied.append(h["id"])

    with open("data.json", "w", encoding="utf-8") as f:
        json.dump(db, f, ensure_ascii=False, separators=(",", ":"))
    print(f"Updated: {len(applied)} — {applied}")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
